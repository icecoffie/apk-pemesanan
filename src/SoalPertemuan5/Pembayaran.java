    void setData(String meja, String total) {
       txtNoMeja.setText(meja);
       txtTotalPesanan.setText(total);
         // HITUNG PPN DI SINI
        int t = Integer.parseInt(total);
        int ppn = t * 11 / 100;

        txtPPN.setText(String.valueOf(ppn));
    }

    public void setDataDetail(
        String meja,

        String menu1, String harga1, String qty1, String sub1,
        String menu2, String harga2, String qty2, String sub2,
        String menu3, String harga3, String qty3, String sub3,

        String total
    ) {
        txtNoMeja.setText(meja);
        txtTotalPesanan.setText(total);

        int t = Integer.parseInt(total);
        int ppn = t * 11 / 100;
        txtPPN.setText(String.valueOf(ppn));

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) Tabel.getModel();

        model.setRowCount(0); // reset tabel

        // Paket 1
        if (!qty1.equals("0") && !qty1.isEmpty()) {
            model.addRow(new Object[]{meja, menu1, harga1, qty1, sub1});
        }

        // Paket 2
        if (!qty2.equals("0") && !qty2.isEmpty()) {
            model.addRow(new Object[]{meja, menu2, harga2, qty2, sub2});
        }

        // Paket 3
        if (!qty3.equals("0") && !qty3.isEmpty()) {
            model.addRow(new Object[]{meja, menu3, harga3, qty3, sub3});
        }
        this.q1 = qty1.isEmpty() ? 0 : Integer.parseInt(qty1);
        this.q2 = qty2.isEmpty() ? 0 : Integer.parseInt(qty2);
        this.q3 = qty3.isEmpty() ? 0 : Integer.parseInt(qty3);
        model.addRow(new Object[]{
            "",
            "",
            "",
            "TOTAL",
            total
        });

        model.addRow(new Object[]{
            "",
            "",
            "",
            "PPN",
            ppn
        });

        model.addRow(new Object[]{
            "",
            "",
            "",
            "TOTAL AKHIR",
            (t + ppn)
        });
    }
    
