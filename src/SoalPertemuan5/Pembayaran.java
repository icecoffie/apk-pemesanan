    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed

       if (inputPembayaran.getText().isEmpty()) {
           javax.swing.JOptionPane.showMessageDialog(null, "Isi uang pembayaran dulu!");
           return;
       }

       int total = Integer.parseInt(txtTotalPesanan.getText());
       int ppn = Integer.parseInt(txtPPN.getText());
       int bayar = Integer.parseInt(inputPembayaran.getText());

       int totalAkhir = total + ppn;


       if (bayar < totalAkhir) {
           javax.swing.JOptionPane.showMessageDialog(null, "Uang tidak cukup!");
           return;
       }

       int kembali = bayar - totalAkhir;
       outputKembali.setText(String.valueOf(kembali));
       
        int totalItem = q1 + q2 + q3;
        String rekomendasi = DecisionTree.getRekomendasi(total, totalItem);
       // ================= STRUK =================
       OutputData.setText(
           "===== STRUK PEMBAYARAN =====\n" +
           "No Meja : " + txtNoMeja.getText() + "\n" +
           "Total   : " + total + "\n" +
           "PPN     : " + ppn + "\n" +
           "Bayar   : " + bayar + "\n" +
           "Kembali : " + kembali + "\n" +
           "============================"
       );
        OutputData.append("\n\n=== ANALISIS KEUANGAN ===\n" + rekomendasi);

       // ================= SIMPAN KE DATABASE =================
       PembayaranDao dao = new PembayaranDao();

       dao.simpan(
           txtNoMeja.getText(),
           total,
           ppn,
           bayar,
           kembali
       );

       // ================= TOTAL PENDAPATAN DARI DB =================
       
       int totalPendapatan = dao.getTotalPendapatan();
       outputPendapatan.setText(String.valueOf(totalPendapatan));
        try {
            OutputData.print();
        } catch (PrinterException ex) {
            Logger.getLogger(Pembayaran.class.getName()).log(Level.SEVERE, null, ex);
        }
       javax.swing.JOptionPane.showMessageDialog(null, "Pembayaran berhasil!");
    }//GEN-LAST:event_btnBayarActionPerformed

