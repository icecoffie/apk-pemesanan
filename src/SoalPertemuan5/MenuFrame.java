    private void loadMenu() {
        JPaket1.removeAllItems();
        JPaket2.removeAllItems();
        JPaket3.removeAllItems();

        for (Menu m : dao.getMenuByKategori("paket1")) {
            JPaket1.addItem(m.getNama());
        }

        for (Menu m : dao.getMenuByKategori("paket2")) {
            JPaket2.addItem(m.getNama());
        }

        for (Menu m : dao.getMenuByKategori("paket3")) {
            JPaket3.addItem(m.getNama());
        }
    }
