    private void btnOkeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOkeActionPerformed
        int h1 = hrgPaket1.getText().isEmpty() ? 0 : Integer.parseInt(hrgPaket1.getText());
        int h2 = hrgPaket2.getText().isEmpty() ? 0 : Integer.parseInt(hrgPaket2.getText());
        int h3 = hrgPaket3.getText().isEmpty() ? 0 : Integer.parseInt(hrgPaket3.getText());
    
        // qty
        int q1 = qtyPaket1.getText().isEmpty() ? 0 : Integer.parseInt(qtyPaket1.getText());
        int q2 = qtyPaket2.getText().isEmpty() ? 0 :Integer.parseInt(qtyPaket2.getText());
        int q3 = qtyPaket3.getText().isEmpty() ? 0 :Integer.parseInt(qtyPaket3.getText());
        
        // total
        int total1 = h1*q1;
        int total2 = h2*q2;
        int total3 = h3*q3;
        
        //bayar
        byrPaket1.setText(String.valueOf(total1));
        byrPaket2.setText(String.valueOf(total2));
        byrPaket3.setText(String.valueOf(total3));
        
        int totalSemua = total1 + total2 + total3;
        inputTotalPesanan.setText(String.valueOf(totalSemua));
    }//GEN-LAST:event_btnOkeActionPerformed

    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed

        if (inputNamaPelanggan.getText().isEmpty() || inputMeja.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(null, "Isi nama dan meja dulu!");
            return;
        }

        if (inputTotalPesanan.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(null, "Hitung total dulu (klik OK)!");
            return;
        }

        PemesananDAO daoPesan = new PemesananDAO();
        DetailPemesananDAO daoDetail = new DetailPemesananDAO();
        MenuDAO menuDAO = new MenuDAO();

        int idPesanan = daoPesan.simpan(
            inputNamaPelanggan.getText(),
            inputMeja.getText(),
            Integer.parseInt(inputTotalPesanan.getText())
        );

        // ================= PAKET 1 =================
        if (!qtyPaket1.getText().isEmpty() && !qtyPaket1.getText().equals("0")) {
            int idMenu1 = menuDAO.getIdByNama(JPaket1.getSelectedItem().toString());

            daoDetail.simpan(
                idPesanan,
                idMenu1,
                Integer.parseInt(qtyPaket1.getText()),
                Integer.parseInt(byrPaket1.getText())
            );
        }

        // ================= PAKET 2 =================
        if (!qtyPaket2.getText().isEmpty() && !qtyPaket2.getText().equals("0")) {
            int idMenu2 = menuDAO.getIdByNama(JPaket2.getSelectedItem().toString());

            daoDetail.simpan(
                idPesanan,
                idMenu2,
                Integer.parseInt(qtyPaket2.getText()),
                Integer.parseInt(byrPaket2.getText())
            );
        }

        // ================= PAKET 3 =================
        if (!qtyPaket3.getText().isEmpty() && !qtyPaket3.getText().equals("0")) {
            int idMenu3 = menuDAO.getIdByNama(JPaket3.getSelectedItem().toString());

            daoDetail.simpan(
                idPesanan,
                idMenu3,
                Integer.parseInt(qtyPaket3.getText()),
                Integer.parseInt(byrPaket3.getText())
            );
        }

        // ================= PINDAH KE PEMBAYARAN =================
        Pembayaran p = new Pembayaran();

        p.setDataDetail(
            inputMeja.getText(),

            JPaket1.getSelectedItem().toString(),
            hrgPaket1.getText(),
            qtyPaket1.getText(),
            byrPaket1.getText(),

            JPaket2.getSelectedItem().toString(),
            hrgPaket2.getText(),
            qtyPaket2.getText(),
            byrPaket2.getText(),

            JPaket3.getSelectedItem().toString(),
            hrgPaket3.getText(),
            qtyPaket3.getText(),
            byrPaket3.getText(),

            inputTotalPesanan.getText()
        );

        getDesktopPane().add(p);
        p.setVisible(true);

        this.dispose();
    }//GEN-LAST:event_btnBayarActionPerformed

